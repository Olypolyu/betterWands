package com.github.olypolyu.betterwands.gui.components;

import net.minecraft.client.gui.GuiElement;

public abstract class BaseElement implements GuiElement {
	protected int y;
	protected int x;
	protected int height;
	protected int width;

	@Override
	public int getX() {
		return x;
	}

	@Override
	public void setX(int x) {
		this.x = x;
	}

	@Override
	public int getY() {
		return y;
	}

	@Override
	public void setY(int y) {
		this.y = y;
	}

	@Override
	public int getHeight() {
		return height;
	}

	@Override
	public void setHeight(int height) {
		this.height = height;
	}

	@Override
	public int getWidth() {
		return width;
	}

	@Override
	public void setWidth(int width) {
		this.width = width;
	}
}
